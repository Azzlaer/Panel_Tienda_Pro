CREATE DATABASE IF NOT EXISTS mitienda CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE mitienda;
CREATE TABLE IF NOT EXISTS usuarios (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 nombre VARCHAR(120) NOT NULL,
 correo VARCHAR(190) NOT NULL UNIQUE,
 password VARCHAR(255) NOT NULL,
 rol ENUM('usuario','admin') NOT NULL DEFAULT 'usuario',
 estado ENUM('activo','bloqueado') NOT NULL DEFAULT 'activo',
 creado_en TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS publicaciones (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 id_usuario INT UNSIGNED NOT NULL,
 titulo VARCHAR(200) NOT NULL,
 descripcion TEXT NOT NULL,
 precio DECIMAL(12,2) NOT NULL DEFAULT 0,
 tipo ENUM('articulo','servicio') NOT NULL,
 imagen VARCHAR(255) DEFAULT NULL,
 estado ENUM('activo','oculto') NOT NULL DEFAULT 'activo',
 fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 INDEX (id_usuario), INDEX (estado), INDEX (tipo),
 CONSTRAINT fk_pub_user FOREIGN KEY(id_usuario) REFERENCES usuarios(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS resenas (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 id_publicacion INT UNSIGNED NOT NULL,
 id_usuario INT UNSIGNED NOT NULL,
 estrellas TINYINT UNSIGNED NOT NULL,
 comentario TEXT,
 fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 INDEX(id_publicacion),
 FOREIGN KEY(id_publicacion) REFERENCES publicaciones(id) ON DELETE CASCADE,
 FOREIGN KEY(id_usuario) REFERENCES usuarios(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS mensajes (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 id_emisor INT UNSIGNED NOT NULL,
 id_receptor INT UNSIGNED NOT NULL,
 contenido TEXT NOT NULL,
 leido TINYINT(1) NOT NULL DEFAULT 0,
 fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 INDEX(id_receptor,leido),
 FOREIGN KEY(id_emisor) REFERENCES usuarios(id) ON DELETE CASCADE,
 FOREIGN KEY(id_receptor) REFERENCES usuarios(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS favoritos (
 id_usuario INT UNSIGNED NOT NULL,
 id_publicacion INT UNSIGNED NOT NULL,
 PRIMARY KEY(id_usuario,id_publicacion),
 FOREIGN KEY(id_usuario) REFERENCES usuarios(id) ON DELETE CASCADE,
 FOREIGN KEY(id_publicacion) REFERENCES publicaciones(id) ON DELETE CASCADE
) ENGINE=InnoDB;
